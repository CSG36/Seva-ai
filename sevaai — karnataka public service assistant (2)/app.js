function appendMessage(text, sender, service) {
  const row = document.createElement("div");
  row.className = `message-row ${sender === "user" ? "user-row" : "assistant-answer"}`;
  if (sender !== "user") {
    const avatar = document.createElement("div");
    avatar.className = "chat-avatar small";
    avatar.textContent = "S";
    row.append(avatar);
  }
  const content = document.createElement("div");
  content.className = "message-content";
  const bubble = document.createElement("div");
  bubble.className = "message-bubble";
  bubble.textContent = text;
  content.append(bubble);
  if (service) {
    const localized = localizedService(service);
    const link = document.createElement("a");
    link.className = "answer-link";
    link.href = service.url;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
    link.textContent = `${translations[currentLanguage].answerLink} ${localized.name} ↗`;
    content.append(link);
  }
  const time = document.createElement("span");
  time.className = "message-time";
  const labels = translations[currentLanguage];
  time.textContent = `${sender === "user" ? labels.you : labels.botName} · ${labels.justNow}`;
  content.append(time);
  row.append(content);
  chatMessages.append(row);
  chatMessages.scrollTop = chatMessages.scrollHeight;
}

function askQuestion(question) {
  const cleaned = question.trim();
  if (!cleaned) return;
  appendMessage(cleaned, "user");
  const answer = findAnswer(cleaned);
  window.setTimeout(() => appendMessage(answer.text, "assistant", answer.service), 250);
}

document.querySelector("#chat-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const input = document.querySelector("#chat-input");
  askQuestion(input.value);
  input.value = "";
});

