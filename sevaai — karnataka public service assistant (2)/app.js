function renderServices() {
  const stopWords = new Set([
    "how", "do", "i", "get", "a", "the", "my", "where", "can", "check", "is", "for", "and",
    "ಹೇಗೆ", "ನನ್ನ", "ನಾನು", "ಎಲ್ಲಿ", "ಇದೆ", "ಗೆ", "ಮತ್ತು", "ಪಡೆಯುವುದು", "ಪಡೆಯಲು", "ಮಾಡುವುದು",
    "कैसे", "करें", "करना", "मैं", "मेरा", "मेरे", "कहाँ", "है", "हैं", "के", "की", "का", "और", "प्राप्त", "चाहिए", "क्या"
  ]);
  const query = currentQuery.trim().toLowerCase().replace(/[?.,!]/g, "").split(/\s+/)
    .filter((term) => term && !stopWords.has(term));
  const matches = services.filter((service) => {
    const matchesCategory = activeCategory === "All" || service.category === activeCategory;
    const localizedText = Object.values(localizedServices[service.name] || {})
      .map((localized) => `${localized.name} ${localized.description} ${localized.keywords}`)
      .join(" ");
    const categoryKey = {
      "Certificates": "categoryCertificates",
      "Land & property": "categoryLand",
      "Benefits": "categoryBenefits",
      "Everyday services": "categoryEveryday"
    }[service.category];
    const categoryNames = ["en", "kn", "hi"].map((language) => translations[language][categoryKey]).join(" ");
    const searchable = `${service.name} ${service.category} ${service.description} ${service.keywords} ${localizedText} ${categoryNames}`.toLowerCase();
    return matchesCategory && query.every((term) => searchable.includes(term));
  });

  serviceGrid.innerHTML = matches.map((service) => {
    const localized = localizedService(service);
    const categoryKey = {
      "Certificates": "categoryCertificates",
      "Land & property": "categoryLand",
      "Benefits": "categoryBenefits",
      "Everyday services": "categoryEveryday"
    }[service.category];
    return `
    <a class="service-card" href="${service.url}" target="_blank" rel="noopener noreferrer" aria-label="${localized.name}, ${translations[currentLanguage].officialSite}">
      <div class="service-card-top"><span class="service-icon" aria-hidden="true">${service.icon}</span><span class="service-arrow" aria-hidden="true">↗</span></div>
      <h3>${localized.name}</h3>
      <p>${localized.description}</p>
      <div class="service-card-bottom"><span class="service-tag">${translations[currentLanguage][categoryKey]}</span><span>${translations[currentLanguage].officialSite} ↗</span></div>
    </a>
  `;
  }).join("");
  emptyState.hidden = matches.length > 0;
  serviceGrid.hidden = matches.length === 0;
}

