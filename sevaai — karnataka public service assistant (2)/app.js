function applyLanguage(language) {
  if (!translations[language]) return;
  currentLanguage = language;
  localStorage.setItem("sevaai-language", language);
  const labels = translations[language];
  document.documentElement.lang = language;
  document.title = labels.pageTitle;
  document.querySelector('meta[name="description"]').content = labels.pageDescription;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = labels[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = labels[element.dataset.i18nPlaceholder];
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", labels[element.dataset.i18nAriaLabel]);
  });
  document.querySelectorAll(".language-button").forEach((button) => {
    const selected = button.dataset.language === language;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  document.querySelectorAll(".popular-searches [data-i18n]").forEach((button) => {
    const key = button.dataset.i18n;
    const queryKey = {
      popularCertificate: "queryCertificate",
      popularLand: "queryLand",
      popularElectricity: "queryElectricity"
    }[key];
    if (queryKey) button.dataset.query = labels[queryKey];
  });
  document.querySelectorAll(".suggestions [data-i18n]").forEach((button) => {
    const questionKey = {
      suggestionCertificate: "suggestionCertificate",
      suggestionLand: "suggestionLand",
      suggestionScheme: "suggestionScheme"
    }[button.dataset.i18n];
    button.dataset.question = labels[questionKey];
  });
  renderServices();
}

document.querySelectorAll(".language-button").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language));
});

